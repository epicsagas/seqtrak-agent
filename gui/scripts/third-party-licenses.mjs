// Writes ../THIRD_PARTY_LICENSES_GUI.md: license texts for packages that can end
// up in the gui/dist bundle (production dependencies plus the Svelte runtime and
// its dependency tree). Over-inclusive on purpose. Run: node scripts/third-party-licenses.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const gui = join(dirname(fileURLToPath(import.meta.url)), '..')
const nm = join(gui, 'node_modules')
const pkg = JSON.parse(readFileSync(join(gui, 'package.json'), 'utf8'))
const roots = [...Object.keys(pkg.dependencies ?? {}), 'svelte']

const seen = new Map()
const visit = (name) => {
  if (seen.has(name)) return
  const dir = join(nm, name)
  const pj = join(dir, 'package.json')
  if (!existsSync(pj)) return
  const meta = JSON.parse(readFileSync(pj, 'utf8'))
  seen.set(name, { dir, meta })
  for (const dep of Object.keys(meta.dependencies ?? {})) visit(dep)
}
roots.forEach(visit)

const licenseText = (dir) => {
  const f = readdirSync(dir).find((n) => /^(licen[cs]e|copying)(\.|$)/i.test(n))
  return f ? readFileSync(join(dir, f), 'utf8').trim() : '(no license file shipped; see package metadata)'
}

const names = [...seen.keys()].sort()
let out = '# Third-party licenses (web GUI)\n\n'
out += 'Generated by `node gui/scripts/third-party-licenses.mjs`. Packages that may be bundled into `gui/dist`.\n\n'
out += '| Package | Version | License |\n|---|---|---|\n'
for (const n of names) {
  const { meta } = seen.get(n)
  out += `| ${n} | ${meta.version} | ${meta.license ?? 'UNKNOWN'} |\n`
}
for (const n of names) {
  const { dir, meta } = seen.get(n)
  out += `\n## ${n} ${meta.version} (${meta.license ?? 'UNKNOWN'})\n\n\`\`\`text\n${licenseText(dir)}\n\`\`\`\n`
}
writeFileSync(join(gui, '..', 'THIRD_PARTY_LICENSES_GUI.md'), out)
console.log(`wrote THIRD_PARTY_LICENSES_GUI.md (${names.length} packages)`)
